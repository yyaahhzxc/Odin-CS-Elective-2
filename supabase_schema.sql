DROP POLICY IF EXISTS "profiles_select_policy" ON public.profiles;
CREATE POLICY "profiles_select_policy" ON public.profiles
    FOR SELECT TO authenticated
    USING (id = auth.uid() OR (SELECT public.is_admin()));

DROP POLICY IF EXISTS "profiles_update_policy" ON public.profiles;
CREATE POLICY "profiles_update_policy" ON public.profiles
    FOR UPDATE TO authenticated
    USING (id = auth.uid() OR (SELECT public.is_admin()))
    WITH CHECK (id = auth.uid() OR (SELECT public.is_admin()));

DROP POLICY IF EXISTS "profiles_insert_policy" ON public.profiles;
CREATE POLICY "profiles_insert_policy" ON public.profiles
    FOR INSERT TO authenticated
    WITH CHECK (id = auth.uid());

-- 7b. roles: Customer & Admin can read; no access when signed out
DROP POLICY IF EXISTS "roles_read_policy" ON public.roles;
CREATE POLICY "roles_read_policy" ON public.roles
    FOR SELECT TO authenticated
    USING (true);

-- 7c. categories: Customer & Admin can read; Admin can add, edit, delete
DROP POLICY IF EXISTS "categories_read_policy" ON public.categories;
CREATE POLICY "categories_read_policy" ON public.categories
    FOR SELECT TO authenticated
    USING (true);

DROP POLICY IF EXISTS "categories_insert_policy" ON public.categories;
CREATE POLICY "categories_insert_policy" ON public.categories
    FOR INSERT TO authenticated
    WITH CHECK ((SELECT public.is_admin()));

DROP POLICY IF EXISTS "categories_update_policy" ON public.categories;
CREATE POLICY "categories_update_policy" ON public.categories
    FOR UPDATE TO authenticated
    USING ((SELECT public.is_admin()))
    WITH CHECK ((SELECT public.is_admin()));

DROP POLICY IF EXISTS "categories_delete_policy" ON public.categories;
CREATE POLICY "categories_delete_policy" ON public.categories
    FOR DELETE TO authenticated
    USING ((SELECT public.is_admin()));

-- 7d. products: Customer & Admin can read; Admin can add, edit, delete
DROP POLICY IF EXISTS "Allow public read access on products" ON public.products;
DROP POLICY IF EXISTS "products read" ON public.products;
CREATE POLICY "products read" ON public.products
    FOR SELECT TO authenticated
    USING (true);

DROP POLICY IF EXISTS "create product" ON public.products;
CREATE POLICY "create product" ON public.products
    FOR INSERT TO authenticated
    WITH CHECK ((SELECT public.is_admin() AS is_admin));

DROP POLICY IF EXISTS "update product" ON public.products;
CREATE POLICY "update product" ON public.products
    FOR UPDATE TO authenticated
    USING ((SELECT public.is_admin() AS is_admin))
    WITH CHECK ((SELECT public.is_admin() AS is_admin));

DROP POLICY IF EXISTS "delete product" ON public.products;
CREATE POLICY "delete product" ON public.products
    FOR DELETE TO authenticated
    USING ((SELECT public.is_admin() AS is_admin));

-- 7e. orders: Customer reads & creates own orders only; Admin reads all & updates status
DROP POLICY IF EXISTS "orders_select_policy" ON public.orders;
CREATE POLICY "orders_select_policy" ON public.orders
    FOR SELECT TO authenticated
    USING (user_id = auth.uid() OR (SELECT public.is_admin()));

DROP POLICY IF EXISTS "orders_insert_policy" ON public.orders;
CREATE POLICY "orders_insert_policy" ON public.orders
    FOR INSERT TO authenticated
    WITH CHECK (user_id = auth.uid() AND NOT (SELECT public.is_admin()));

DROP POLICY IF EXISTS "orders_update_admin_policy" ON public.orders;
CREATE POLICY "orders_update_admin_policy" ON public.orders
    FOR UPDATE TO authenticated
    USING ((SELECT public.is_admin()))
    WITH CHECK ((SELECT public.is_admin()));

-- 7f. order_items: Customer reads items of own orders; Admin reads all
DROP POLICY IF EXISTS "order_items_select_policy" ON public.order_items;
CREATE POLICY "order_items_select_policy" ON public.order_items
    FOR SELECT TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.orders o
            WHERE o.id = order_items.order_id
              AND (o.user_id = auth.uid() OR (SELECT public.is_admin()))
        )
    );

DROP POLICY IF EXISTS "order_items_insert_policy" ON public.order_items;
CREATE POLICY "order_items_insert_policy" ON public.order_items
    FOR INSERT TO authenticated
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.orders o
            WHERE o.id = order_items.order_id
              AND o.user_id = auth.uid()
              AND NOT (SELECT public.is_admin())
        )
    );

